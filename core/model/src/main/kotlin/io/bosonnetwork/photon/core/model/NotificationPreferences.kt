package io.bosonnetwork.photon.core.model

/** User notification preferences (design spec 4.7, M6-6). */
data class NotificationPreferences(
    /** Master switch for incoming-message notifications (the ongoing service notice is unaffected). */
    val enabled: Boolean = true,
    /** When false, notifications hide the sender/content and show a generic message. */
    val showPreview: Boolean = true,
)
